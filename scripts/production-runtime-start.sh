#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd -P)"
ENV_FILE="$ROOT/.env"
PROJECTS_COMPOSE="$ROOT/config/projects.compose.yaml"
CORE_COMPOSE="$ROOT/compose.yaml"

fail() { printf 'PRODUCTION_RUNTIME_START=FAIL reason=%s\n' "$1" >&2; exit 1; }
require_file() { [[ -f "$1" && ! -L "$1" ]] || fail "required regular file missing"; }

require_file "$ENV_FILE"
require_file "$PROJECTS_COMPOSE"
require_file "$CORE_COMPOSE"
[[ "$(stat -c '%a' "$ENV_FILE")" == '600' ]] || fail '.env must be mode 0600'

# Generated by the installer and owner-private. shellcheck disable=SC1090
set -a
source "$ENV_FILE"
set +a

for key in GIT_REVISION GATEWAY_IMAGE GATEWAY_IMAGE_ID DOCKER_AUTHORITY_IMAGE DOCKER_AUTHORITY_IMAGE_ID EXECUTOR_IMAGE EXECUTOR_IMAGE_ID PROJECTS_WORK_IMAGE PROJECTS_WORK_IMAGE_ID INTERNAL_TOKEN DOCKER_AUTHORITY_TOKEN AGENT_KIRO_KEY_FILE; do
  [[ -n "${!key:-}" ]] || fail "required runtime value missing: $key"
done
[[ "$INTERNAL_TOKEN" != "$DOCKER_AUTHORITY_TOKEN" ]] || fail 'authority tokens must be distinct'
for key in GATEWAY_IMAGE_ID DOCKER_AUTHORITY_IMAGE_ID EXECUTOR_IMAGE_ID PROJECTS_WORK_IMAGE_ID; do
  [[ "${!key}" =~ ^sha256:[0-9a-f]{64}$ ]] || fail "invalid immutable image id: $key"
done
for key in GATEWAY_IMAGE DOCKER_AUTHORITY_IMAGE EXECUTOR_IMAGE PROJECTS_WORK_IMAGE; do
  [[ "${!key}" != *':latest' ]] || fail "mutable image reference refused: $key"
done

docker info >/dev/null 2>&1 || fail 'Docker daemon unavailable'
[[ -S /var/run/docker.sock ]] || fail 'Docker socket unavailable'
export DOCKER_GID="$(stat -c '%g' /var/run/docker.sock)"
export QG_RUNTIME_UID="$(id -u)"
export QG_RUNTIME_GID="$(id -g)"

[[ -f "$AGENT_KIRO_KEY_FILE" && ! -L "$AGENT_KIRO_KEY_FILE" ]] || fail 'Kiro secret backing file missing or unsafe'
[[ "$(stat -c '%u' "$AGENT_KIRO_KEY_FILE")" == "$QG_RUNTIME_UID" ]] || fail 'Kiro secret backing file owner mismatch'
[[ "$(stat -c '%a' "$AGENT_KIRO_KEY_FILE")" == '600' ]] || fail 'Kiro secret backing file must be mode 0600'
kiro_size="$(stat -c '%s' "$AGENT_KIRO_KEY_FILE")"
[[ "$kiro_size" =~ ^[0-9]+$ && "$kiro_size" -le 1024 ]] || fail 'Kiro secret backing file exceeds bound'

verify_image() {
  local ref="$1" expected="$2" actual
  actual="$(docker image inspect "$ref" --format '{{.Id}}' 2>/dev/null)" || fail "required local image unavailable: $ref"
  [[ "$actual" == "$expected" ]] || fail "local image identity mismatch: $ref"
}
verify_image "$GATEWAY_IMAGE" "$GATEWAY_IMAGE_ID"
verify_image "$DOCKER_AUTHORITY_IMAGE" "$DOCKER_AUTHORITY_IMAGE_ID"
verify_image "$EXECUTOR_IMAGE" "$EXECUTOR_IMAGE_ID"
verify_image "$PROJECTS_WORK_IMAGE" "$PROJECTS_WORK_IMAGE_ID"

core_args=(docker compose --env-file "$ENV_FILE" -p quarangate -f "$CORE_COMPOSE")
projects_args=(docker compose --env-file "$ENV_FILE" -p quarangate-projects -f "$PROJECTS_COMPOSE")
started=0
completed=0
cleanup_partial() {
  local rc=$?
  trap - EXIT
  if (( started )) && (( ! completed )); then
    "${core_args[@]}" down --remove-orphans >/dev/null 2>&1 || true
    "${projects_args[@]}" down --remove-orphans >/dev/null 2>&1 || true
  fi
  exit "$rc"
}
trap cleanup_partial EXIT

"${projects_args[@]}" config >/dev/null
"${core_args[@]}" config >/dev/null
started=1
"${projects_args[@]}" up -d --no-build --pull never
"${core_args[@]}" up -d --no-build --pull never

wait_healthy() {
  local service="$1" deadline=$((SECONDS + 120)) id state
  while (( SECONDS < deadline )); do
    id="$("${core_args[@]}" ps -q "$service")"
    if [[ -n "$id" ]]; then
      state="$(docker inspect "$id" --format '{{if .State.Health}}{{.State.Health.Status}}{{else}}{{.State.Status}}{{end}}' 2>/dev/null || true)"
      [[ "$state" == 'healthy' ]] && return 0
    fi
    sleep 1
  done
  return 1
}
for service in docker-authority executor gateway; do
  wait_healthy "$service" || fail "core service not healthy: $service"
done

for pair in \
  "gateway|$GATEWAY_IMAGE_ID" \
  "docker-authority|$DOCKER_AUTHORITY_IMAGE_ID" \
  "executor|$EXECUTOR_IMAGE_ID"; do
  IFS='|' read -r service expected <<<"$pair"
  id="$("${core_args[@]}" ps -q "$service")"
  [[ -n "$id" ]] || fail "core service missing: $service"
  [[ "$(docker inspect "$id" --format '{{.Image}}')" == "$expected" ]] || fail "live core image mismatch: $service"
done

mapfile -t project_ids < <("${projects_args[@]}" ps -q)
(( ${#project_ids[@]} > 0 )) || fail 'no enrolled project target started'
for id in "${project_ids[@]}"; do
  [[ "$(docker inspect "$id" --format '{{.State.Running}}')" == 'true' ]] || fail 'project target not running'
  [[ "$(docker inspect "$id" --format '{{.Image}}')" == "$PROJECTS_WORK_IMAGE_ID" ]] || fail 'project target image mismatch'
done

completed=1
trap - EXIT
printf 'PRODUCTION_RUNTIME_SOURCE=%s\n' "$GIT_REVISION"
printf 'PRODUCTION_RUNTIME_CORE=HEALTHY\n'
printf 'PRODUCTION_RUNTIME_PROJECTS=%s\n' "${#project_ids[@]}"
printf 'PRODUCTION_RUNTIME_START=PASS\n'
